_PREP = r"(?i:в|во|на|из|над|под|около|у|близ|возле|по)"
_STEMS = "|".join("(?:%s)" % st for st, _ in sorted(PLACES, key=lambda x: -len(x[0])))
FOREIGN_RE = re.compile(r"\b" + _PREP + r"\s+(" + _STEMS + r")\w*")
_COMPILED = [(re.compile(st), nom) for st, nom in PLACES]


def nominative(text):
    """«Германии» → «Германия»; неизвестное слово возвращается как есть."""
    t = (text or "").strip()
    for rx, nom in _COMPILED:
        if rx.match(t):
            return nom
    return t


def find(title, text):
    """Название места (именительный падеж), если текст про другую страну, иначе None."""
    m = FOREIGN_RE.search(title) or FOREIGN_RE.search((text or "")[:260])
    return nominative(m.group(1)) if m else None
